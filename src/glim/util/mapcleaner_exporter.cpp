bool export_mapcleaner_dataset(
    const std::string& output_dir,
    const std::vector<SubMap::Ptr>& submaps,
    MapCleanerExportStats* stats) {
  MapCleanerExportStats local_stats;
  local_stats.submaps = submaps.size();

  std::filesystem::create_directories(output_dir);
  std::filesystem::create_directories(output_dir + "/scans");
  std::filesystem::create_directories(output_dir + "/result");

  std::ofstream traj_lidar_ofs(output_dir + "/traj_lidar.txt");
  if (!traj_lidar_ofs) {
    if (stats) {
      *stats = local_stats;
    }
    return false;
  }

  std::size_t scan_id = 0;

  for (const auto& submap : submaps) {
    if (!submap) {
      continue;
    }

    const auto* keyframes = submap->get_custom_data<MapCleanerKeyframes>(MAPCLEANER_KEYFRAMES_KEY);

    if (keyframes && !keyframes->empty()) {
      local_stats.submaps_with_keyframes++;
      local_stats.keyframes_seen += keyframes->size();

      for (const auto& keyframe : *keyframes) {
        if (!keyframe.cloud || keyframe.cloud->size() == 0) {
          local_stats.skipped_empty_frames++;
          continue;
        }

        const std::string filename = scan_filename(scan_id);
        const std::string pcd_path = output_dir + "/scans/" + filename;

        if (!write_scan(pcd_path, *keyframe.cloud)) {
          local_stats.skipped_empty_frames++;
          continue;
        }

        const Eigen::Isometry3d T_world_lidar =
          submap->T_world_origin * keyframe.T_origin_lidar;

        write_tum_frame(traj_lidar_ofs, keyframe.stamp, T_world_lidar);

        scan_id++;
        local_stats.scans_written++;
        local_stats.poses_written++;
      }

      continue;
    }

    // Fallback for passthrough / future dumps that actually keep frame clouds.
    if (submap->frames.empty()) {
      continue;
    }

    const Eigen::Isometry3d T_world_endpoint_L =
      submap->T_world_origin * submap->T_origin_endpoint_L;

    const Eigen::Isometry3d T_odom_imu0 = submap->frames.front()->T_world_imu;

    for (const auto& frame : submap->frames) {
      local_stats.frames_seen++;

      if (!frame || !frame->frame || frame->frame->size() == 0) {
        local_stats.skipped_empty_frames++;
        continue;
      }

      const Eigen::Isometry3d T_world_imu =
        T_world_endpoint_L * T_odom_imu0.inverse() * frame->T_world_imu;

      const Eigen::Isometry3d T_world_lidar =
        T_world_imu * frame->T_lidar_imu.inverse();

      const std::string filename = scan_filename(scan_id);
      const std::string pcd_path = output_dir + "/scans/" + filename;

      if (!write_scan(pcd_path, *frame->frame)) {
        local_stats.skipped_empty_frames++;
        continue;
      }

      write_tum_frame(traj_lidar_ofs, frame->stamp, T_world_lidar);

      scan_id++;
      local_stats.scans_written++;
      local_stats.poses_written++;
    }
  }

  write_loader_yaml(output_dir, local_stats.scans_written);
  write_readme(output_dir, local_stats.scans_written);

  if (stats) {
    *stats = local_stats;
  }

  return true;
}

