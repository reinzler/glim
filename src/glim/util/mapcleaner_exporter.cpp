void write_tum_frame(std::ofstream& ofs, const double stamp, const Eigen::Isometry3d& pose) {
  const Eigen::Quaterniond quat(pose.linear());
  const Eigen::Vector3d trans(pose.translation());

  ofs << boost::format("%.9f %.6f %.6f %.6f %.6f %.6f %.6f %.6f")
           % stamp
           % trans.x()
           % trans.y()
           % trans.z()
           % quat.x()
           % quat.y()
           % quat.z()
           % quat.w()
      << std::endl;
}

std::string scan_filename(const std::size_t scan_id) {
  std::ostringstream ss;
  ss << std::setw(6) << std::setfill('0') << scan_id << ".pcd";
  return ss.str();
}

void write_loader_yaml(const std::string& output_dir, const std::size_t num_scans) {
  std::ofstream ofs(output_dir + "/loader_glim.yaml");

  ofs << "# Generated by GLIM rover core MapCleaner exporter\n";
  ofs << "loader:\n";
  ofs << "  pcds_dir: \"" << output_dir << "/scans\"\n";
  ofs << "  pose_file: \"" << output_dir << "/traj_lidar.txt\"\n";
  ofs << "  kitti_calibration_file: \"\"\n";
  ofs << "  start: 0\n";
  ofs << "  end: " << (num_scans == 0 ? -1 : static_cast<long long>(num_scans) - 1) << "\n";
  ofs << "  format: \"glim\"\n";
  ofs << "\n";
  ofs << "map_cleaner:\n";
  ofs << "  save_dir: \"" << output_dir << "/result\"\n";
}

void write_readme(const std::string& output_dir, const std::size_t num_scans) {
  std::ofstream ofs(output_dir + "/README.md");

  ofs << "# GLIM to MapCleaner export\n\n";
  ofs << "Generated files:\n\n";
  ofs << "- `scans/*.pcd`: individual GLIM keyframe clouds in LiDAR-local coordinates.\n";
  ofs << "- `traj_lidar.txt`: TUM-style LiDAR poses aligned one-to-one with `scans/*.pcd`.\n";
  ofs << "- `loader_glim.yaml`: MapCleaner loader snippet.\n\n";
  ofs << "Number of scans: " << num_scans << "\n";
}

bool write_scan(
    const std::string& path,
    const gtsam_points::PointCloud& cloud) {
  if (cloud.size() == 0) {
    return false;
  }

  if (cloud.has_intensities()) {
    return save_pcd_xyzi(path, cloud);
  }

  return save_pcd_xyz(path, cloud);
}

